dash::coin::BlockType block_from_hex(const char* hex)
{
    std::string h(hex);
    std::vector<unsigned char> raw;
    raw.reserve(h.size() / 2);
    for (size_t i = 0; i + 1 < h.size(); i += 2)
        raw.push_back(static_cast<unsigned char>(
            std::stoul(h.substr(i, 2), nullptr, 16)));
    ::PackStream ps(raw);
    dash::coin::BlockType blk;
    ps >> blk;
    return blk;
}

// Re-digest a mutated payload so a test can isolate the field it is probing
// from the digest guard (otherwise EVERY mutation would merely prove the
// digest works).
std::string reseal(std::string payload)
{
    const size_t at = payload.find("digest ");
    if (at == std::string::npos) return payload;
    const size_t eol = payload.find('\n', at);
    std::string stripped = payload.substr(0, at) + payload.substr(eol + 1);
    const std::string d = mn_checkpoint_digest(stripped);
    return payload.substr(0, at) + "digest " + d + payload.substr(eol);
}

// Replace the first occurrence of `from` with `to`, then reseal.
std::string mutate(const std::string& payload, const std::string& from,
                   const std::string& to, bool reseal_it = true)
{
    std::string p = payload;
    const size_t at = p.find(from);
    EXPECT_NE(at, std::string::npos) << "mutation anchor not found: " << from;
    if (at == std::string::npos) return p;
    p.replace(at, from.size(), to);
    return reseal_it ? reseal(p) : p;
}

// ── A driveable harness around the lane ────────────────────────────────────
// Stands in for main_dash's seams: a synthetic header chain (height -> hash),
// a block store the request seam serves from, and a capture of what the lane
// publishes.
struct BridgeHarness {
    MnCheckpointLane lane;
    std::map<uint32_t, uint256>                    headers;   // height -> hash
    std::map<uint32_t, dash::coin::BlockType>      blocks;    // height -> body
    uint32_t tip{0};
    std::vector<uint32_t> requested;
    bool     published{false};
    uint32_t published_as_of{0};
    std::vector<std::pair<uint256, MNState>> published_set;
    // When set, request_block_fn delivers the block INLINE (the ordered-stream
    // behaviour of a real peer answering getdata on one TCP connection).
    bool auto_deliver{true};

    BridgeHarness()
    {
        lane.set_tip_height_fn([this] { return tip; });
        lane.set_header_hash_at_fn(
            [this](uint32_t h) -> std::optional<uint256> {
                auto it = headers.find(h);
                if (it == headers.end()) return std::nullopt;
                return it->second;
            });
        lane.set_publish_fn(
            [this](std::vector<std::pair<uint256, MNState>> set, uint32_t as_of) {
                published = true;
                published_as_of = as_of;
                published_set = std::move(set);
            });
        lane.set_request_block_fn([this](uint32_t h) {
            requested.push_back(h);
            if (!auto_deliver) return;
            auto it = blocks.find(h);
            if (it == blocks.end()) return;
            lane.on_block_connected(it->second, h);
        });
    }
};

