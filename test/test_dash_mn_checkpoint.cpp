// ═══════════════════════════════════════════════════════════════════════════
// 4. The bridge: real anchor + real blocks -> published set.
// ═══════════════════════════════════════════════════════════════════════════
TEST(DashMnCheckpointBridge, ReplaysRealBlocksAndPublishesAtTip)
{
    BridgeHarness h;
    h.headers[kAnchorHeight] = uint256S(kAnchorHash);
    h.blocks[1519544] = block_from_hex(kBlockHex1519544);
    h.blocks[1519545] = block_from_hex(kBlockHex1519545);
    h.blocks[1519546] = block_from_hex(kBlockHex1519546);
    h.tip = 1519546;

    h.lane.arm(good_checkpoint());
    EXPECT_EQ(h.lane.state(), MnCheckpointLane::State::Waiting);

    h.lane.pump();

    ASSERT_TRUE(h.published) << "bridge status: " << h.lane.status();
    EXPECT_EQ(h.lane.state(), MnCheckpointLane::State::Published);
    EXPECT_EQ(h.published_as_of, 1519546u)
        << "the published snapshot must be labelled with the height it bridged"
           " to, or the maintainer's apply cursor starts wrong";
    EXPECT_EQ(h.published_set.size(), 6u);

    // dashd's actual payment schedule over those three blocks (the same
    // attribution the E2c suite pins against the RPC seed).
    std::map<uint256, MNState> out(h.published_set.begin(), h.published_set.end());
    EXPECT_EQ(out.at(uint256S("dc2e02ac95ce4ccc9843c38de7bdaf32f2a1d5966c05412"
                              "7a3f4ca4f4bbd5991")).nLastPaidHeight, 1519544u);
    EXPECT_EQ(out.at(uint256S("9b653e767b978c10346d938c08dc8c5acd03c495f9d913e"
                              "6fc652bfcae11a348")).nLastPaidHeight, 1519545u);
    EXPECT_EQ(out.at(uint256S("91bbce94c34ebde0d099c0a2cb7635c0c31425ebabcec64"
                              "4f4f1a0854bfa605d")).nLastPaidHeight, 1519546u);

    // The blocks were requested in ascending order from the cursor.
    ASSERT_FALSE(h.requested.empty());
    EXPECT_EQ(h.requested.front(), 1519544u);
    EXPECT_TRUE(std::is_sorted(h.requested.begin(), h.requested.end()));
}

TEST(DashMnCheckpointBridge, IgnoresLiveTipBlocksArrivingMidBridge)
{
    // The cold-start race: the new_block inv leg delivers a block at the CURRENT
    // tip while the bridge is still replaying history. Folding it would advance
    // a stale cursor -- the E4-soak bad-cb-payee shape.
    BridgeHarness h;
    h.auto_deliver = false;
    h.headers[kAnchorHeight] = uint256S(kAnchorHash);
    h.tip = 1519546;
    h.lane.arm(good_checkpoint());
    h.lane.pump();
    ASSERT_EQ(h.lane.state(), MnCheckpointLane::State::Bridging);

    // A far-future block arrives first. It must be ignored, NOT folded.
    h.lane.on_block_connected(block_from_hex(kBlockHex1519546), 1519546);
    EXPECT_EQ(h.lane.state(), MnCheckpointLane::State::Bridging)
        << "an out-of-order live block must not fail or advance the bridge";
    EXPECT_EQ(h.lane.cursor_height(), kAnchorHeight);
    EXPECT_FALSE(h.published);

    // Now the ordered replay proceeds normally.
    h.lane.on_block_connected(block_from_hex(kBlockHex1519544), 1519544);
    h.lane.on_block_connected(block_from_hex(kBlockHex1519545), 1519545);
    h.lane.on_block_connected(block_from_hex(kBlockHex1519546), 1519546);
    EXPECT_TRUE(h.published) << h.lane.status();
    EXPECT_EQ(h.published_as_of, 1519546u);
}

TEST(DashMnCheckpointBridge, ChainPositionMismatchFailsClosed)
{
    // The anchor names a block our PoW-validated header chain does not hold at
    // that height: wrong chain, wrong fork, or a fabricated anchor.
    BridgeHarness h;
    h.headers[kAnchorHeight] = uint256S(
        "00000000000000000000000000000000000000000000000000000000deadbeef");
    h.tip = 1519546;
    h.lane.arm(good_checkpoint());
    h.lane.pump();

    EXPECT_EQ(h.lane.state(), MnCheckpointLane::State::FailedClosed);
    EXPECT_NE(h.lane.status().find("CHAIN-POSITION MISMATCH"), std::string::npos)
        << h.lane.status();
    EXPECT_FALSE(h.published);
    // Terminal: further drives must not resurrect it.
    h.headers[kAnchorHeight] = uint256S(kAnchorHash);
    h.lane.pump();
    EXPECT_EQ(h.lane.state(), MnCheckpointLane::State::FailedClosed);
    EXPECT_FALSE(h.published);
}

