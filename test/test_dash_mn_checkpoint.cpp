// ═══════════════════════════════════════════════════════════════════════════
// 5. End-to-end through the REAL leg-4 event, plus the negative control.
// ═══════════════════════════════════════════════════════════════════════════
namespace {

// Mirrors main_dash's wiring: the lane publishes into Node::mn_list_update,
// leg 4 carries it to the maintainer, leg 2 supplies the tip.
struct E2eRig {
    dash::interfaces::Node                        node;
    dash::coin::NodeCoinState                     state;
    dash::coin::CoinStateMaintainer               maint{state};
    std::vector<std::shared_ptr<EventDisposable>> subs;
    BridgeHarness                                 h;

    E2eRig()
    {
        // The anti-mint latch main_dash enables for the embedded arm.
        maint.set_require_seeded_mn_set(true);
        subs.push_back(c2pool::dash::wire_mn_list_ingest(node, maint));
        subs.push_back(c2pool::dash::wire_tip_ingest(node, maint));
        h.lane.set_publish_fn(
            [this](std::vector<std::pair<uint256, MNState>> set, uint32_t as_of) {
                dash::interfaces::MnListUpdate up;
                up.mnstates     = std::move(set);
                up.as_of_height = as_of;
                node.mn_list_update.happened(up);
            });
        h.headers[kAnchorHeight] = uint256S(kAnchorHash);
        h.blocks[1519544] = block_from_hex(kBlockHex1519544);
        h.blocks[1519545] = block_from_hex(kBlockHex1519545);
        h.blocks[1519546] = block_from_hex(kBlockHex1519546);
        h.tip = 1519546;
    }

    void fire_tip()
    {
        dash::interfaces::TipAdvance ta;
        ta.prev_height           = 1519546;
        ta.prev_hash             = uint256S(kAnchorHash);
        ta.bits_for_next         = 0x1d00ffff;
        ta.mtp_at_tip            = 1751000000;
        ta.address_version       = TESTNET_PUBKEY_VER;
        ta.address_p2sh_version  = TESTNET_P2SH_VER;
        node.new_tip.happened(ta);
    }
};

} // namespace

TEST(DashMnCheckpointE2e, BridgePublishFlipsPopulatedThroughTheRealLeg4Event)
{
    E2eRig r;
    EXPECT_FALSE(r.state.populated()) << "cold start must not be populated";

    r.h.lane.arm(good_checkpoint());
    r.h.lane.pump();
    ASSERT_EQ(r.h.lane.state(), MnCheckpointLane::State::Published)
        << r.h.lane.status();

    r.fire_tip();

    EXPECT_TRUE(r.state.populated())
        << "the bridged masternode set + a live tip must flip the embedded arm";
}

// NEGATIVE CONTROL. Identical wiring; the ONLY difference is a corrupted
// anchor. If this ever passes populated()==true, the fail-closed path is
// decorative.
TEST(DashMnCheckpointE2e, NegativeControlCorruptAnchorLeavesArmUnpopulated)
{
    E2eRig r;
    std::string tampered = mutate(kRealCheckpoint1519543,
                                  "1519459", "1519999", /*reseal_it=*/false);
    auto bad = parse_mn_checkpoint(tampered, "testnet");
    ASSERT_FALSE(bad.ok);

    r.h.lane.arm(bad);
    r.h.lane.pump();
    EXPECT_EQ(r.h.lane.state(), MnCheckpointLane::State::FailedClosed);

    r.fire_tip();

    EXPECT_FALSE(r.state.populated())
        << "a refused anchor must leave the embedded arm unarmed -- templates"
           " keep routing to the dashd fallback";
}

// Second negative control, one layer down: prove the anti-mint latch main_dash
// enables actually blocks the "one accidental ProRegTx arms the queue" path.
TEST(DashMnCheckpointE2e, NegativeControlAntiMintLatchBlocksUnseededArming)
{
    dash::coin::NodeCoinState state;
    dash::coin::CoinStateMaintainer maint{state};
    maint.set_require_seeded_mn_set(true);

    // A non-empty masternode set with NO height stamp: what an unauthoritative
    // source (or a block-connect registration) would produce.
    auto cp = good_checkpoint();
    maint.on_mn_list_update(cp.entries, /*as_of_height=*/0);

    auto fire_tip = [&maint] {
        maint.on_new_tip(/*prev_height=*/1519546, uint256S(kAnchorHash),
                         /*bits_for_next=*/0x1d00ffff,
                         /*mtp_at_tip=*/1751000000,
                         TESTNET_PUBKEY_VER, TESTNET_P2SH_VER);
    };
    fire_tip();

    EXPECT_FALSE(state.populated())
        << "an unheighted masternode set must never arm the embedded arm";

    // Positive control on the same object: the SAME set WITH its height arms it.
    maint.on_mn_list_update(cp.entries, kAnchorHeight);
    fire_tip();
    EXPECT_TRUE(state.populated())
        << "a height-stamped authoritative snapshot must still arm normally";
}
