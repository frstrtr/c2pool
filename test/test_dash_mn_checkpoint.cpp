TEST(DashMnCheckpoint, UnpinnedPayloadIsReportedDistinctly)
{
    // What a fresh checkout ships: a comment-only .inc.
    auto cp = parse_mn_checkpoint("", "mainnet");
    EXPECT_FALSE(cp.ok);
    EXPECT_TRUE(cp.unpinned) << "an absent anchor must not look like corruption";
    EXPECT_NE(cp.error.find("UNPINNED"), std::string::npos);

    auto cp2 = parse_mn_checkpoint("# nothing here\n\n# still nothing\n", "mainnet");
    EXPECT_FALSE(cp2.ok);
    EXPECT_TRUE(cp2.unpinned);
}

TEST(DashMnCheckpoint, DigestMismatchRefusesEverything)
{
    // Flip ONE masternode's lastPaidHeight without resealing: exactly the shape
    // of a hand edit or a half-applied merge.
    std::string tampered = mutate(kRealCheckpoint1519543,
                                  "1519459", "1519999", /*reseal_it=*/false);
    auto cp = parse_mn_checkpoint(tampered, "testnet");
    EXPECT_FALSE(cp.ok);
    EXPECT_FALSE(cp.unpinned);
    EXPECT_NE(cp.error.find("DIGEST MISMATCH"), std::string::npos) << cp.error;
    EXPECT_TRUE(cp.entries.empty()) << "no partial set may survive a refusal";
}

