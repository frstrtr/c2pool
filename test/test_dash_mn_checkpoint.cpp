TEST(DashMnCheckpointBridge, ReplayGapFailsClosed)
{
    // Blocks skipped mid-replay: dashd advanced its payment queue at heights we
    // never folded, so ours is silently behind. Never publish.
    BridgeHarness h;
    h.auto_deliver = false;
    h.headers[kAnchorHeight] = uint256S(kAnchorHash);
    h.tip = 1519546;
    h.lane.arm(good_checkpoint());
    h.lane.pump();
    ASSERT_EQ(h.lane.state(), MnCheckpointLane::State::Bridging);

    h.lane.on_block_connected(block_from_hex(kBlockHex1519544), 1519544);
    EXPECT_EQ(h.lane.cursor_height(), 1519544u);
    // 1519545 never arrives; the lane is waiting for it, so 1519546 is simply
    // ignored and the bridge NEVER publishes.
    h.lane.on_block_connected(block_from_hex(kBlockHex1519546), 1519546);
    EXPECT_FALSE(h.published);
    EXPECT_EQ(h.lane.state(), MnCheckpointLane::State::Bridging);
    EXPECT_EQ(h.lane.cursor_height(), 1519544u);
}

TEST(DashMnCheckpointBridge, PayeeDesyncOnWrongAnchorFailsClosed)
{
    // THE anchor falsification test. Corrupt the anchor so it projects the
    // wrong payee, then replay a real block. The block's real coinbase does not
    // pay what we project -> the anchor is proven wrong -> terminal refusal.
    // This is what stops a bad trust anchor from ever reaching a template.
    //
    // 1519459 is dc2e02ac's lastPaidHeight, the LOWEST in the set, which is why
    // dashd paid it at 1519544. Pushing it to the top of the queue makes some
    // OTHER masternode our projected payee.
    std::string p = mutate(kRealCheckpoint1519543, " 838365 1519459 ",
                           " 838365 1519543 ");
    auto bad = parse_mn_checkpoint(p, "testnet");
    ASSERT_TRUE(bad.ok) << bad.error;  // structurally valid, semantically wrong

    BridgeHarness h;
    h.headers[kAnchorHeight] = uint256S(kAnchorHash);
    h.blocks[1519544] = block_from_hex(kBlockHex1519544);
    h.tip = 1519544;
    h.lane.arm(bad);
    h.lane.pump();

    EXPECT_EQ(h.lane.state(), MnCheckpointLane::State::FailedClosed)
        << h.lane.status();
    EXPECT_NE(h.lane.status().find("PAYEE DESYNC"), std::string::npos)
        << h.lane.status();
    EXPECT_FALSE(h.published)
        << "a falsified anchor must NEVER reach the maintainer";
}

