///
/// THE GAP THIS CLOSES: E2c gave the payout-bearing DMN set exactly one
/// cold-start source, dashd RPC `protx list valid true`. With no RPC the arm
/// printed "seed UNAVAILABLE" and every template kept routing to the dashd
/// fallback -- the last structurally daemon-dependent input on the daemonless
/// path. mn_checkpoint.hpp + mn_checkpoint_lane.hpp replace the RPC with a
/// release-pinned anchor replayed forward through the existing block-connect
/// ingest.
///
/// The anchor is a TRUST ANCHOR (see mn_checkpoint.hpp and
/// src/impl/dash/coin/checkpoints/README.md). This suite pins the parts that
/// are NOT trusted -- every local check, and every way the load can refuse.
///
/// Pinned here, network-free, against REAL captured testnet data:
///   * the committed fixture (test/dash_mn_checkpoint_testnet_1519543.inc,
///     produced by tools/dash/gen_mn_checkpoint.py from a real
///     `protx list valid true 1519543`) parses, and the resulting MNStates are
///     FIELD-IDENTICAL to what the E2c RPC parser produces from the same
///     dashd JSON -- the checkpoint seed and the RPC seed are the same set;
///   * fail-closed on every defect class: unpinned, bad magic, unknown key,
