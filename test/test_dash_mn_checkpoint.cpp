    const auto cp = build_ondemand_scenario(rig);
    rig.h.lane.set_ondemand_fold_cap(0);      // no repair -> stop ON the mismatch

    rig.h.lane.arm(cp);
    rig.h.lane.pump();
    ASSERT_EQ(rig.h.lane.state(), MnCheckpointLane::State::FailedClosed)
        << rig.h.lane.status();

