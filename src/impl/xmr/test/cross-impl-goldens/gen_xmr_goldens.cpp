// src/impl/xmr/test/cross-impl-goldens/gen_xmr_goldens.cpp
//   XMR-lane (Family B) golden-vector GENERATOR — the analogue of
//   tools/gen_decay_canonical.py. A one-shot developer tool (NOT a CI target):
//   it recomputes every captured XMR-lane output through the merged consensus
//   primitives (xmr_goldens_compute.hpp) and emits the frozen golden artifacts:
//
//       ./gen_xmr_goldens          -> prints xmr_lane_goldens_golden.hpp to stdout
//       ./gen_xmr_goldens --json   -> prints the xmr_lane_goldens.json manifest
//
//   Regenerate ONLY after a deliberate, reviewed change to a captured output;
//   the load-bearing gate is xmr_goldens_kat, which compares the live recompute
//   to the emitted header.
// ---------------------------------------------------------------------------
#include <cstdio>
#include <cstring>
#include <string>

#include "xmr_goldens_compute.hpp"

using namespace xmr_goldens;

static void emit_header(const XmrGoldens& g) {
    std::printf(
"// SPDX-License-Identifier: AGPL-3.0-or-later\n"
"// Copyright (c) 2026, The c2pool developers (frstrtr/c2pool)\n"
"//\n"
"// This file is part of c2pool and is distributed under the terms of the GNU\n"
"// Affero General Public License, version 3 or (at your option) any later\n"
"// version. See COPYING in the repository root.\n"
"//\n"
"// ---------------------------------------------------------------------------\n"
"// src/impl/xmr/test/cross-impl-goldens/xmr_lane_goldens_golden.hpp\n"
"//   FROZEN golden vectors for the XMR/RandomX v37 lane (Family B) -- the\n"
"//   Family-B analogue of proto/refimpl/golden/decay_table_canonical_golden_v1.\n"
"//   GENERATED by gen_xmr_goldens.cpp; do not hand-edit. LOAD-BEARING: the\n"
"//   xmr_goldens_kat recomputes each value live and byte-compares it here, so a\n"
"//   code change that shifts any captured XMR-lane output turns the KAT red.\n"
"//   Cross-anchors: G2_D == monero tests/crypto/tests.txt vector 1; G1 bits ==\n"
"//   the hand-verified accept/reject column of xmr_difficulty_kat.\n"
"// ---------------------------------------------------------------------------\n"
"#pragma once\n"
"\n"
"#include <cstddef>\n"
"#include <cstdint>\n"
"\n"
"namespace xmr_goldens {\n"
"namespace golden {\n"
"\n");
    std::printf("inline constexpr char G1_DIFFICULTY_BITS[] = \"%s\";\n\n", g.g1_bits.c_str());
    std::printf("inline constexpr char        G2_D[]   = \"%s\";\n", g.g2_D.c_str());
    std::printf("inline constexpr char        G2_P0[]  = \"%s\";\n", g.g2_P0.c_str());
    std::printf("inline constexpr std::uint8_t G2_VT0  = 0x%02x;\n\n", g.g2_vt0);
    std::printf("inline constexpr char G3_R[]       = \"%s\";\n", g.g3_r.c_str());
    std::printf("inline constexpr char G3_R_PUB[]   = \"%s\";\n", g.g3_R.c_str());
    std::printf("inline constexpr char G3_MM_ROOT[] = \"%s\";\n", g.g3_mm_root.c_str());
    std::printf("inline constexpr char G3_PCB0[]    = \"%s\";\n\n", g.g3_Pcb.c_str());
    std::printf("} // namespace golden\n} // namespace xmr_goldens\n");
}

static void emit_json(const XmrGoldens& g) {
    std::printf("{\n");
    std::printf("  \"_provenance\": \"XMR-lane (Family B) golden vectors; regenerated by gen_xmr_goldens.cpp\",\n");
    std::printf("  \"g1_difficulty_bits\": \"%s\",\n", g.g1_bits.c_str());
    std::printf("  \"g2_stealth\": { \"D\": \"%s\", \"P0\": \"%s\", \"view_tag0\": \"%02x\" },\n",
                g.g2_D.c_str(), g.g2_P0.c_str(), g.g2_vt0);
    std::printf("  \"g3_coinbase\": { \"r\": \"%s\", \"R\": \"%s\", \"mm_root\": \"%s\", \"P_cb0\": \"%s\" }\n",
                g.g3_r.c_str(), g.g3_R.c_str(), g.g3_mm_root.c_str(), g.g3_Pcb.c_str());
    std::printf("}\n");
}

int main(int argc, char** argv) {
    XmrGoldens g = compute_xmr_goldens();
    if (argc > 1 && std::strcmp(argv[1], "--json") == 0) emit_json(g);
    else emit_header(g);
    return 0;
}
